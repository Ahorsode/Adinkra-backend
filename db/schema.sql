-- Adinkra Airways schema for PostgreSQL (Neon).
-- Timestamps are stored as ISO-8601 UTC text ("2026-11-20T10:15:00.000Z"), exactly as the
-- original SQLite app did, so string comparisons and slicing in the code keep working.

CREATE OR REPLACE FUNCTION iso_now() RETURNS text LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  phone text,
  national_id_enc text,
  -- Sign-in is handled by Neon Auth (neon_auth schema); this links the app profile to that account.
  auth_user_id text UNIQUE,
  -- Legacy column from the pre-Neon-Auth version; no longer written.
  password_hash text,
  role text NOT NULL DEFAULT 'traveler' CHECK (role IN ('traveler','staff','admin')),
  permissions text NOT NULL DEFAULT '[]',
  active integer NOT NULL DEFAULT 1,
  passport_enc text,
  passport_expiry text,
  nationality text,
  dob text,
  frequent_flyer_no text,
  emergency_name text,
  emergency_relation text,
  emergency_phone text,
  created_at text NOT NULL DEFAULT iso_now(),
  last_login text
);
-- Upgrade databases created before Neon Auth (both statements are no-ops on a fresh database).
ALTER TABLE users ADD COLUMN IF NOT EXISTS auth_user_id text UNIQUE;
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- Unused since Neon Auth took over sessions; kept so older databases upgrade cleanly.
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ip text,
  created_at text NOT NULL DEFAULT iso_now(),
  expires_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
CREATE TABLE IF NOT EXISTS airports (
  code text PRIMARY KEY,
  name text NOT NULL,
  city text NOT NULL,
  country text NOT NULL,
  zone text NOT NULL CHECK (zone IN ('GH','WA','INTL'))
);
CREATE TABLE IF NOT EXISTS routes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_no text NOT NULL UNIQUE,
  origin text NOT NULL REFERENCES airports(code),
  destination text NOT NULL REFERENCES airports(code),
  segment text NOT NULL CHECK (segment IN ('DOMESTIC','REGIONAL','INTERNATIONAL')),
  base_price double precision NOT NULL,
  duration_min integer NOT NULL,
  aircraft text NOT NULL,
  dep_time text NOT NULL,
  days text NOT NULL,
  active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE TABLE IF NOT EXISTS flights (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id integer NOT NULL REFERENCES routes(id),
  flight_no text NOT NULL,
  departure text NOT NULL,
  arrival text NOT NULL,
  aircraft text NOT NULL,
  base_price double precision NOT NULL,
  status text NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED','CANCELLED')),
  delay_min integer NOT NULL DEFAULT 0,
  gate text,
  terminal text,
  remarks text,
  cargo_capacity_kg integer NOT NULL,
  UNIQUE (flight_no, departure)
);
CREATE INDEX IF NOT EXISTS idx_flights_route_dep ON flights(route_id, departure);
CREATE INDEX IF NOT EXISTS idx_flights_dep ON flights(departure);
CREATE INDEX IF NOT EXISTS idx_flights_arr ON flights(arrival);
CREATE TABLE IF NOT EXISTS bookings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pnr text NOT NULL UNIQUE,
  user_id integer REFERENCES users(id),
  contact_email text,
  contact_phone text,
  trip_type text NOT NULL CHECK (trip_type IN ('ONE_WAY','ROUND_TRIP')),
  tier text NOT NULL,
  segment text NOT NULL,
  status text NOT NULL CHECK (status IN ('HELD','CONFIRMED','CANCELLED','EXPIRED')),
  total double precision NOT NULL,
  taxes double precision NOT NULL DEFAULT 0,
  hold_expires text,
  created_at text NOT NULL DEFAULT iso_now(),
  updated_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS idx_bookings_user ON bookings(user_id);
CREATE INDEX IF NOT EXISTS idx_bookings_held ON bookings(hold_expires) WHERE status = 'HELD';
CREATE INDEX IF NOT EXISTS idx_bookings_created ON bookings(created_at, status, segment);
CREATE TABLE IF NOT EXISTS booking_flights (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  flight_id integer NOT NULL REFERENCES flights(id),
  direction text NOT NULL CHECK (direction IN ('OUT','RET')),
  fare double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_bf_flight ON booking_flights(flight_id);
CREATE INDEX IF NOT EXISTS idx_bf_booking ON booking_flights(booking_id);
CREATE TABLE IF NOT EXISTS passengers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  first_name text NOT NULL,
  last_name text NOT NULL,
  dob text,
  nationality text,
  passport_enc text,
  passport_expiry text,
  pax_type text NOT NULL DEFAULT 'ADULT'
);
CREATE INDEX IF NOT EXISTS idx_pax_booking ON passengers(booking_id);
CREATE TABLE IF NOT EXISTS tickets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_no text NOT NULL UNIQUE,
  passenger_id integer NOT NULL REFERENCES passengers(id) ON DELETE CASCADE,
  booking_flight_id integer NOT NULL REFERENCES booking_flights(id) ON DELETE CASCADE,
  seat text NOT NULL,
  status text NOT NULL CHECK (status IN ('HELD','CONFIRMED','BOARDED','CANCELLED')),
  boarded_at text,
  boarded_by integer REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_tickets_bf ON tickets(booking_flight_id);
CREATE INDEX IF NOT EXISTS idx_tickets_pax ON tickets(passenger_id);
CREATE TABLE IF NOT EXISTS cargo (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  awb text NOT NULL UNIQUE,
  user_id integer REFERENCES users(id),
  shipper_name text NOT NULL,
  shipper_phone text NOT NULL,
  shipper_email text,
  consignee_name text NOT NULL,
  consignee_phone text NOT NULL,
  origin text NOT NULL,
  destination text NOT NULL,
  description text NOT NULL,
  cargo_type text NOT NULL,
  pieces integer NOT NULL,
  weight_kg double precision NOT NULL,
  length_cm double precision NOT NULL,
  width_cm double precision NOT NULL,
  height_cm double precision NOT NULL,
  chargeable_kg double precision NOT NULL,
  price double precision NOT NULL,
  status text NOT NULL,
  flight_id integer REFERENCES flights(id),
  notes text,
  created_at text NOT NULL DEFAULT iso_now(),
  updated_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS idx_cargo_flight ON cargo(flight_id);
CREATE INDEX IF NOT EXISTS idx_cargo_user ON cargo(user_id);
CREATE TABLE IF NOT EXISTS payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer REFERENCES bookings(id),
  cargo_id integer REFERENCES cargo(id),
  kind text NOT NULL CHECK (kind IN ('BOOKING','CHANGE','CARGO')),
  method text NOT NULL,
  provider text,
  account_masked text,
  amount double precision NOT NULL,
  status text NOT NULL CHECK (status IN ('SUCCESS','FAILED')),
  txn_ref text NOT NULL,
  message text,
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS idx_pay_booking ON payments(booking_id);
CREATE INDEX IF NOT EXISTS idx_pay_created ON payments(created_at, status, booking_id, amount, method, provider);
CREATE INDEX IF NOT EXISTS idx_pay_cargo ON payments(cargo_id);
CREATE TABLE IF NOT EXISTS refunds (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer NOT NULL REFERENCES bookings(id),
  amount double precision NOT NULL,
  pct integer NOT NULL,
  reason text,
  processed_by integer REFERENCES users(id),
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS idx_refunds_booking ON refunds(booking_id);
CREATE TABLE IF NOT EXISTS cargo_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cargo_id integer NOT NULL REFERENCES cargo(id) ON DELETE CASCADE,
  status text NOT NULL,
  note text,
  actor_id integer REFERENCES users(id),
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS idx_cargo_events ON cargo_events(cargo_id);
CREATE TABLE IF NOT EXISTS support_tickets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref text NOT NULL UNIQUE,
  user_id integer NOT NULL REFERENCES users(id),
  category text NOT NULL,
  subject text NOT NULL,
  pnr text,
  status text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED','CLOSED')),
  assigned_to integer REFERENCES users(id),
  created_at text NOT NULL DEFAULT iso_now(),
  updated_at text NOT NULL DEFAULT iso_now()
);
CREATE TABLE IF NOT EXISTS ticket_messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id integer NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
  author_id integer REFERENCES users(id),
  author_role text NOT NULL,
  body text NOT NULL,
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS idx_ticket_messages ON ticket_messages(ticket_id);
CREATE TABLE IF NOT EXISTS notifications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id),
  channel text NOT NULL CHECK (channel IN ('EMAIL','SMS')),
  recipient text NOT NULL,
  subject text NOT NULL,
  body text NOT NULL,
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id);
CREATE TABLE IF NOT EXISTS audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id),
  action text NOT NULL,
  target text,
  details text,
  severity text NOT NULL DEFAULT 'info' CHECK (severity IN ('info','warn','high')),
  ip text,
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log(created_at);
CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value text NOT NULL
);
-- Login / lookup throttling. Workers run in many isolates, so the counters live in the database.
CREATE TABLE IF NOT EXISTS rate_limits (
  key text PRIMARY KEY,
  count integer NOT NULL,
  until_ms bigint NOT NULL
);
